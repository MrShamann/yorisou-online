// A deterministic, loopback-only OpenAI-compatible endpoint for the OSF-1 harnesses.
//
// WHY THIS EXISTS, AND WHY IT NEEDED NO NEW CODE PATH.
//
// The Reflection Assistant's draft state and its provider-failure state are two of the screens §15
// asks to be scanned and §16 asks to be reachable by keyboard. Neither is reachable with providers
// off, which is their default and their production state — the route calls draftReflection() with the
// Provider Harness resolver and there is deliberately no way to inject a fake through HTTP.
//
// The resolver already supports a configurable base URL, because a self-hosted or proxied provider is
// a real deployment shape:
//
//   YORISOU_PRIVATE_AI_PROVIDER_PRIMARY=openrouter_shared
//   OPENROUTER_BASE_URL=http://127.0.0.1:<port>
//   OPENROUTER_API_KEY=<generated by the harness>
//
// So this is a PROVIDER, reached the way every provider is reached. No test-only branch exists in the
// application, no environment variable selects a fake inside the product, and nothing here is
// importable by application code. That distinction is the whole point: a fake provider selectable by
// configuration inside the app is a fake provider that can be selected in production.
//
// DETERMINISM WITHOUT A CONTROL CHANNEL. The behaviour is a pure function of the prompt, so a spec
// chooses it by what it types into the reflection rather than by calling a switch:
//
//   prompt contains FAIL_MARKER      -> 500, so the flow shows 「いまは整理を利用できません」
//   prompt contains BOUNDARY_MARKER  -> a draft that crosses the AI boundary, which must be DISCARDED
//   otherwise                        -> a valid, bounded draft built from nothing but fixed text
//
//   node tests/life-os/disposable-provider.mjs <port>

import { createServer } from "node:http";

const port = Number.parseInt(process.argv[2] ?? "0", 10);
if (!port) {
  console.error("usage: node tests/life-os/disposable-provider.mjs <port>");
  process.exit(1);
}

export const FAIL_MARKER = "PROVIDERFAILS";
export const BOUNDARY_MARKER = "PROVIDERCROSSES";

// Fixed text. It says nothing about the person and adds no facts — the draft a compliant model would
// return for "organise what I wrote", without depending on what was written.
const DRAFT = "書かれたことを、起きた順に整理しました。まず出来事があり、そのあとで感じたことが書かれています。";
const QUESTION = "次に同じことが起きたら、どうしたいですか。";
// Deliberately across the boundary: 「あなたは〜な人です」 is a personality attribution, which
// inspectAiOutput must catch before it reaches a surface.
const OVER_THE_LINE = "あなたは考えすぎてしまう人です。";

function reply(res, status, body) {
  const payload = JSON.stringify(body);
  res.writeHead(status, { "Content-Type": "application/json", "Content-Length": Buffer.byteLength(payload) });
  res.end(payload);
}

createServer((req, res) => {
  const chunks = [];
  req.on("data", (chunk) => chunks.push(chunk));
  req.on("end", () => {
    const raw = Buffer.concat(chunks).toString("utf8");
    if (raw.includes(FAIL_MARKER)) {
      // A provider that is up and refusing. The normalized reason is `provider_http_error`, and the
      // person is told the assistant is unavailable and keeps everything they wrote.
      return reply(res, 500, { error: { message: "simulated provider failure" } });
    }
    const draft = raw.includes(BOUNDARY_MARKER) ? OVER_THE_LINE : DRAFT;
    return reply(res, 200, {
      choices: [{ message: { content: JSON.stringify({ draft, question: QUESTION }) } }],
      usage: { prompt_tokens: 0, completion_tokens: 0 },
    });
  });
  req.on("error", () => reply(res, 400, { error: { message: "bad request" } }));
}).listen(port, "127.0.0.1", () => {
  process.stdout.write(`disposable-provider listening on 127.0.0.1:${port}\n`);
});
